"""Generate the read-only builtin definition catalog from the exact pinned SDK."""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys

os.environ["LITELLM_LOCAL_MODEL_COST_MAP"] = "True"
os.environ["OPENHANDS_SUPPRESS_BANNER"] = "1"

parser = argparse.ArgumentParser()
parser.add_argument("source", type=Path)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
source = args.source.resolve()
root = Path(__file__).resolve().parents[2]
manifest = json.loads((root / "transpile/upstream.json").read_text())
commit = subprocess.check_output(["git", "-C", str(source), "rev-parse", "HEAD"], text=True).strip()
expected = manifest["commit"]
if commit != expected:
    raise SystemExit(f"Source commit {commit} does not match pinned {expected}")
if subprocess.check_output(["git", "-C", str(source), "status", "--porcelain"], text=True).strip():
    raise SystemExit("Source checkout must be clean")
sys.path[:0] = [str(source / name) for name in ("openhands-sdk", "openhands-tools", "openhands-workspace")]
from openhands.tools.preset import default as preset  # noqa: E402
if Path(preset.__file__).resolve() != source / "openhands-tools/openhands/tools/preset/default.py":
    raise SystemExit("Imported preset module is not from the pinned source checkout")

catalog = []
hashes = {}
for definition in preset.discover_builtin_agents(enable_browser=True):
    value = definition.model_dump(mode="json", context={"expose_secrets": True})
    path = Path(value["source"])
    relative = path.relative_to(source).as_posix()
    # Distribution-stable metadata, never a machine-specific build checkout path.
    value["source"] = relative
    hashes[relative] = hashlib.sha256(path.read_bytes()).hexdigest()
    catalog.append(value)
catalog.sort(key=lambda item: item["source"])
metadata = {"repository": "OpenHands/software-agent-sdk", "commit": commit,
            "factory": "openhands-tools/openhands/tools/preset/default.py::discover_builtin_agents",
            "files": hashes}
output = "// Generated by scripts/parity/generate-builtin-agents.py. Do not edit.\n"
output += "import type { AgentDefinitionOptions } from './index.js';\n\n"
output += "export const builtinAgentSource = " + json.dumps(metadata, ensure_ascii=False, indent=2) + " as const;\n\n"
output += "export const builtinAgentCatalog: readonly AgentDefinitionOptions[] = " + json.dumps(catalog, ensure_ascii=False, indent=2) + ";\n"
target = root / "src/subagent/builtin-catalog.ts"
if args.check:
    if not target.exists() or target.read_text() != output:
        raise SystemExit("Builtin agent catalog differs from the pinned source")
else:
    target.write_text(output)
print(f"{'Verified' if args.check else 'Generated'} {len(catalog)} builtin definitions at {commit}")
